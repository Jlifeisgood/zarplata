# Packs the official template (template_11101_20.xltx from my.soliq.uz) into android\web\tpl11101.js.
# Every part of the package goes in as base64; the app injects rows into sheet1.xml at runtime and writes a plain xlsx
# (SheetJS would drop the template styles). Keep this file ASCII-only (Windows PowerShell 5.1).
param([Parameter(Mandatory = $true)][string]$Template, [string]$Out = '')

$ErrorActionPreference = 'Stop'
if (-not $Out) { $Out = Join-Path (Split-Path -Parent $PSScriptRoot) 'android\web\tpl11101.js' }
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$zip = [IO.Compression.ZipFile]::OpenRead($Template)
$parts = [ordered]@{}
try {
    foreach ($e in $zip.Entries) {
        if ($e.FullName -like 'xl/calcChain.xml') { continue }   # chain is rebuilt by Excel; stale chain breaks the file
        $ms = New-Object IO.MemoryStream
        $s = $e.Open(); $s.CopyTo($ms); $s.Dispose()
        $bytes = $ms.ToArray()
        if ($e.FullName -eq '[Content_Types].xml') {
            $t = [Text.Encoding]::UTF8.GetString($bytes)
            $t = $t.Replace('spreadsheetml.template.main+xml', 'spreadsheetml.sheet.main+xml')
            $t = [regex]::Replace($t, '<Override PartName="/xl/calcChain.xml"[^>]*/>', '')
            $bytes = [Text.Encoding]::UTF8.GetBytes($t)
        }
        elseif ($e.FullName -eq 'xl/_rels/workbook.xml.rels') {
            $t = [Text.Encoding]::UTF8.GetString($bytes)
            $t = [regex]::Replace($t, '<Relationship [^>]*calcChain[^>]*/>', '')
            $bytes = [Text.Encoding]::UTF8.GetBytes($t)
        }
        elseif ($e.FullName -eq 'xl/workbook.xml') {
            $t = [Text.Encoding]::UTF8.GetString($bytes)
            $t = $t.Replace('<calcPr calcId="191029"/>', '<calcPr calcId="191029" fullCalcOnLoad="1"/>')
            $bytes = [Text.Encoding]::UTF8.GetBytes($t)
        }
        $parts[$e.FullName] = [Convert]::ToBase64String($bytes)
    }
}
finally { $zip.Dispose() }

$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('/* Official template 11101_20 (appendices 4 and 5) from my.soliq.uz: generated by tools/gen-template.ps1, do not edit */')
[void]$sb.AppendLine('window.TPL_FILES = {')
$i = 0
foreach ($k in $parts.Keys) {
    $i++
    $comma = if ($i -lt $parts.Count) { ',' } else { '' }
    [void]$sb.AppendLine('  "' + $k + '": "' + $parts[$k] + '"' + $comma)
}
[void]$sb.AppendLine('};')
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
Write-Host ("Wrote {0} parts, {1:N0} KB" -f $parts.Count, ((Get-Item $Out).Length / 1KB))
